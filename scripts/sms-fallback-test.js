'use strict';
const assert=require('assert');
process.env.ZOVRO_SMS_MODE='mock';
const sms=require('../backend/sms-fallback');
(async()=>{
 for(const v of ['1',' موافق ','YES','accept','نعم'])assert.equal(sms.classifyReply(v),'accept');
 for(const v of ['2','رفض','لا أريد','NO','decline'])assert.equal(sms.classifyReply(v),'decline');
 for(const v of ['STOP','إيقاف','إلغاء'])assert.equal(sms.classifyReply(v),'stop');
 for(const v of ['HELP','مساعدة'])assert.equal(sms.classifyReply(v),'help');
 assert.equal(sms.classifyReply('hello'),'unknown');
 assert.equal(sms.normalizeE164('+1 (313) 555-0123'),'+13135550123');
 assert.equal(sms.normalizeE164('3135550123'),null);
 const user={id:'p1',role:'provider',accountStatus:'active',availability:true,phoneVerified:true,smsJobAlertsOptIn:true,smsOptedOut:false,phone:'+13135550123'};
 assert.equal(sms.smsEligible(user),true);
 assert.equal(sms.smsEligible({...user,smsJobAlertsOptIn:false}),false);
 assert.equal(sms.smsEligible({...user,smsOptedOut:true}),false);
 const consentUser={...user,smsJobAlertsOptIn:false,smsConsent:{consentedAt:new Date().toISOString(),policyVersion:'2026-09'}};
 assert.equal(sms.smsEligible(consentUser),true);
 assert.equal(sms.smsEligible({...consentUser,smsConsent:{...consentUser.smsConsent,optedOutAt:new Date().toISOString()}}),false);
 const offer=sms.createOffer({requestId:'r1',providerId:'p1'});
 const mock=new sms.MockSmsProvider();
 const sent=await sms.sendJobOffer({smsProvider:mock,user,offer,service:'Roadside assistance'});
 assert.equal(sent.mock,true);assert.equal(mock.sent.length,1);assert.equal(mock.sent[0].to.includes('5550123'),false);assert.match(mock.sent[0].body,/ZOVRO:/);assert.match(mock.sent[0].body,/STOP/);
 assert.deepEqual(sms.evaluateAcceptance({offer,providerUser:user,request:{id:'r1',status:'Open',providerId:null}}),{ok:true});
 assert.equal(sms.evaluateAcceptance({offer,providerUser:{...user,availability:false},request:{id:'r1',status:'Open',providerId:null}}).reason,'provider_unavailable');
 assert.equal(sms.evaluateAcceptance({offer,providerUser:user,request:{id:'r1',status:'Assigned',providerId:'p2'}}).reason,'job_unavailable');
 const expired={...offer,expiresAt:new Date(Date.now()-1000).toISOString()};
 assert.equal(sms.evaluateAcceptance({offer:expired,providerUser:user,request:{id:'r1',status:'Open',providerId:null}}).reason,'offer_expired');
 const token='test_auth_token',url='https://zovro.net/api/webhooks/twilio/sms',params={Body:'1',From:'+13135550123',MessageSid:'SM123'};
 const signature=sms.twilioSignature(token,url,params);
 assert.equal(sms.verifyTwilioSignature({authToken:token,url,params,signature}),true);
 assert.equal(sms.verifyTwilioSignature({authToken:token,url,params:{...params,Body:'2'},signature}),false);
 assert.equal(sms.replyIdempotencyKey('SM123'),sms.replyIdempotencyKey('SM123'));
 assert.notEqual(sms.replyIdempotencyKey('SM123'),sms.replyIdempotencyKey('SM124'));
 console.log('sms-fallback-test: PASS (mock only; no real messages sent)');
})().catch(e=>{console.error(e);process.exit(1)});
