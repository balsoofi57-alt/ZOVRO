'use strict';
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const fail=m=>{throw new Error('native-push-readiness-check: '+m)};
const pkg=JSON.parse(read('package.json'));
const cap=JSON.parse(read('capacitor.config.json'));
const prep=read('scripts/prepare-mobile.js');
const patch=read('scripts/patch-native.js');
const client=read('push-client.js');
if(cap.appId!=='com.zovro.app')fail('unexpected Capacitor appId');
if(!pkg.dependencies?.['@onesignal/capacitor-plugin'])fail('OneSignal Capacitor plugin dependency missing');
if(!prep.includes("'push-client.js'"))fail('push-client.js is not bundled into mobile output');
if(!patch.includes('android.permission.POST_NOTIFICATIONS'))fail('Android notification permission patch missing');
if(!client.includes('7992b022-6c11-4a66-bad4-8cbd114266d0'))fail('verified OneSignal App ID missing from mobile client');
if(!client.includes('requestPermission'))fail('notification permission request missing');
if(!client.includes('externalId')&&!client.includes('externalId:userId'))fail('OneSignal external user identity binding missing');
if(!client.includes('notificationOpened'))fail('notification-open routing missing');
console.log('native-push-readiness-check: PASS');
