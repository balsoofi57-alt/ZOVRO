'use strict';
const assert=require('assert');
const catalog=require('../src/service-catalog');
const features=require('../src/product-features');
const workflows=require('../src/advanced-workflows');
assert(Array.isArray(catalog.SERVICE_CATALOG)&&catalog.SERVICE_CATALOG.length>=9,'Expected full category catalog');
assert(catalog.ALL_SERVICES.length>=80,'Expected expanded service list');
assert(catalog.smartMatch("my car won't start")[0].service.id==='jump-start','Smart Match should detect jump start');
assert(catalog.smartMatch('my basement flooded')[0].service.id==='water-damage','Smart Match should detect water damage');
assert(features.BRAND.slogan==='ANYWHERE. ANYTIME. NEAR YOU.','Approved slogan missing');
assert(features.BRAND.defaultLanguage==='en'&&features.BRAND.languages.join(',')==='en,es','Language policy mismatch');
assert(features.PRODUCT_FEATURES.launchCore.sosDispatch,'SOS must stay enabled');
const estimate=workflows.createEstimate({requestId:'r1',providerId:'p1',labor:100,parts:25,tax:7.5});
assert(estimate.total===132.5,'Estimate total mismatch');
assert(workflows.approveEstimate(estimate).status==='approved','Estimate approval failed');
const order=workflows.createChangeOrder({requestId:'r1',providerId:'p1',title:'Extra work',amount:40});
assert(workflows.approveChangeOrder(order).status==='approved','Change-order approval failed');
const pin=workflows.createJobPin();assert(/^\d{4}$/.test(pin)&&workflows.checkJobPin(pin,pin),'Job PIN failed');
assert(workflows.serviceQualityScore({rating:5,completedJobs:50,onTimeRate:1,cancellationRate:0,responseRate:1})===100,'Quality score failed');
const vehicle=workflows.savedVehicle({year:2024,make:'Ford',model:'F-150',vin:'abc123',nickname:'Work Truck'});
assert(vehicle.vin==='ABC123'&&vehicle.make==='Ford','Saved vehicle normalization failed');
const property=workflows.savedProperty({label:'Home',address:'123 Main St',type:'home'});
assert(property.type==='home'&&property.address==='123 Main St','Saved property failed');
const fav=workflows.favoriteProvider({customerId:'c1',providerId:'p1'});
let favorites=workflows.addFavoriteProvider([],fav);
favorites=workflows.addFavoriteProvider(favorites,fav);
assert(favorites.length===1&&workflows.isFavoriteProvider(favorites,{customerId:'c1',providerId:'p1'}),'Favorite provider workflow failed');
favorites=workflows.removeFavoriteProvider(favorites,{customerId:'c1',providerId:'p1'});
assert(favorites.length===0,'Favorite provider removal failed');
const rebook=workflows.createRebookRequest({previousRequest:{id:'r1',customerId:'c1',providerId:'p1',service:'Plumbing',category:'Home Services'}});
assert(rebook.status==='draft'&&rebook.rebookOfRequestId==='r1'&&rebook.providerId==='p1','Rebook workflow failed');
const recurring=workflows.recurringSchedule({frequency:'monthly',interval:1,nextDate:'2026-09-15T12:00:00.000Z'});
const advanced=workflows.advanceRecurringSchedule(recurring);
assert(advanced.nextDate==='2026-10-15T12:00:00.000Z','Recurring schedule advance failed');
assert(workflows.pauseRecurringSchedule(recurring).active===false&&workflows.resumeRecurringSchedule(recurring).active===true,'Recurring pause/resume failed');
console.log(JSON.stringify({ok:true,categories:catalog.SERVICE_CATALOG.length,services:catalog.ALL_SERVICES.length,smartMatch:true,advancedWorkflows:true,favorites:true,rebook:true,savedAssets:true,recurringServices:true,brand:features.BRAND.name}));
