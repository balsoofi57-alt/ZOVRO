'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html'),theme=read('website-final.css'),website=read('website-final.js');
const features=require('../src/product-features.js');
const listing=JSON.parse(read('store/listing.en-US.json'));
assert(html.includes('<section id="home"')&&html.includes('<section id="profile"'),'Home and Profile must remain');
const home=html.split('<section id="home">')[1]?.split('<section id="jobs"')[0]||'';
const more=html.split('<section id="profile"')[1]?.split('</section>')[0]||'';
assert(!home.includes('id="sosButton"'),'SOS must remain outside the Home screen');
assert(more.includes('id="moreSettings"')&&more.includes('id="sosButton"'),'Secondary SOS entry must remain inside Profile > More options');
assert((html.match(/id="sosButton"/g)||[]).length===1,'Only one secondary SOS entry is allowed');
assert(html.includes('function startUrgentRoadside(){return startRequestWithLocation({service:\'Roadside Assistance\',useLocation:false,urgent:true})}'),'SOS shortcut must use normal reviewed roadside request flow');
assert(html.includes("if(options.urgent===true)$('reqUrgent').checked=true;"),'SOS shortcut must preselect urgent request');
assert(html.includes('Opens a roadside request marked urgent for you to review and send'),'SOS helper must not imply immediate emergency dispatch');
assert(theme.includes('#profile .z-secondary-assistance #sosButton'),'Secondary SOS styling is missing');
assert(!website.includes('id="sosButton"'),'Website enhancement must not place SOS on Home');
assert.equal(features.PRODUCT_FEATURES.launchCore.sosDispatch,false,'SOS launch flag must be disabled');
assert(!listing.apple.description.includes('SOS')&&!listing.googlePlay.fullDescription.includes('SOS'),'Store listing advertises retired SOS');
assert(html.includes('startRequestWithLocation'),'Standard roadside request flow must remain');
assert(read('backend/server-core.js').includes("if(b.source==='sos')return json(res,410"),'New SOS requests must be rejected');
console.log('SOS remains in More options as reviewed urgent roadside request; backend direct SOS dispatch stays disabled.');
