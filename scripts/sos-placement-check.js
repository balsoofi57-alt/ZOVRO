'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const theme=fs.readFileSync(path.join(root,'website-final.css'),'utf8');
const enhancement=fs.readFileSync(path.join(root,'website-final.js'),'utf8');
const home=html.split('<section id="home">')[1]?.split('<section id="jobs"')[0]||'';
const profile=html.split('<section id="profile"')[1]?.split('</section>')[0]||'';
assert.ok(home&&profile,'Home and Profile must exist');
assert.doesNotMatch(home,/id="sosButton"|id="sosHelp"|id="sosStatus"|id="sosView"/,'Home must not expose SOS action or status');
assert.match(profile,/<details id="moreSettings"[^>]*>/,'SOS must be inside collapsed More options on Profile');
assert.match(profile,/<summary>More options<\/summary>/);
assert.match(profile,/id="sosButton"[^>]*onclick="quickSOS\(\)"/,'SOS action must remain usable');
for(const id of ['sosHelp','sosStatus','sosView'])assert.match(profile,new RegExp('id="'+id+'"'),'SOS details remain next to action');
assert.equal((html.match(/id="sosButton"/g)||[]).length,1,'One SOS button only');
assert.doesNotMatch(enhancement,/id="sosButton"/,'Hero renderer cannot recreate an SOS button');
assert.doesNotMatch(enhancement,/\.z-smart-actions'\)\.appendChild\(sos\)/,'Silver layout cannot move SOS into Smart Match');
assert.doesNotMatch(enhancement,/smart\.appendChild\(el\)/,'Silver layout cannot move SOS feedback into Smart Match');
assert.match(enhancement,/menu\.insertBefore\(moreOptions,support\)/,'Secondary assistance must stay within More menu');
assert.match(theme,/#profile \.z-secondary-assistance #sosButton/);
console.log('SOS UI placement: only in More > More options; action and request feedback preserved.');
